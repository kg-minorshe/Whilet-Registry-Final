def set_docx_layout(doc: Document) -> None:
    sec = doc.sections[0]
    sec.top_margin = Cm(2)
    sec.bottom_margin = Cm(2)
    sec.left_margin = Cm(2.5)
    sec.right_margin = Cm(1.5)
    style = doc.styles["Normal"]
    style.font.name = "Arial"
    style.font.size = Pt(11)


def add_common_docx(doc: Document) -> None:
    for key, value in COMMON.items():
        p = doc.add_paragraph()
        p.paragraph_format.space_after = Pt(1)
        r = p.add_run(f"{key}: ")
        r.bold = True
        p.add_run(value)


def make_docx(item: dict) -> Path:
    path = OUT / f"{item['num']}_{item['slug']}.docx"
    doc = Document()
    set_docx_layout(doc)
    title = doc.add_paragraph()
    title.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = title.add_run(item["title"])
    run.bold = True
    run.font.size = Pt(15)
    doc.add_paragraph()
    add_common_docx(doc)
    doc.add_paragraph()
    for heading, paragraphs in item["sections"]:
        h = doc.add_paragraph()
        hr = h.add_run(heading)
        hr.bold = True
        hr.font.size = Pt(12)
        for text in paragraphs:
            p = doc.add_paragraph(text)
            p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
            p.paragraph_format.first_line_indent = Cm(1.25)
            p.paragraph_format.space_after = Pt(6)
    doc.save(path)
    return path


def register_font() -> str:
    candidates = [
        "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf",
        "/usr/share/fonts/dejavu/DejaVuSans.ttf",
    ]
    for candidate in candidates:
        if Path(candidate).exists():
            pdfmetrics.registerFont(TTFont("DejaVu", candidate))
            return "DejaVu"
    return "Helvetica"


def make_pdf(item: dict, font: str) -> Path:
    path = OUT / f"{item['num']}_{item['slug']}.pdf"
    styles = getSampleStyleSheet()
    title_style = ParagraphStyle("TitleRu", parent=styles["Title"], fontName=font, fontSize=14, leading=18, alignment=TA_CENTER, spaceAfter=12)
    h_style = ParagraphStyle("HeadingRu", parent=styles["Heading2"], fontName=font, fontSize=11, leading=14, spaceBefore=8, spaceAfter=5)
    body_style = ParagraphStyle("BodyRu", parent=styles["BodyText"], fontName=font, fontSize=9.5, leading=13, alignment=TA_JUSTIFY, firstLineIndent=8 * mm, spaceAfter=5)
    meta_style = ParagraphStyle("MetaRu", parent=styles["BodyText"], fontName=font, fontSize=9, leading=12, spaceAfter=2)
    pdf = SimpleDocTemplate(str(path), pagesize=A4, leftMargin=22 * mm, rightMargin=16 * mm, topMargin=18 * mm, bottomMargin=18 * mm)
    story = [Paragraph(item["title"], title_style)]
    for key, value in COMMON.items():
        story.append(Paragraph(f"<b>{key}:</b> {value}", meta_style))
    story.append(Spacer(1, 6))
    for heading, paragraphs in item["sections"]:
        story.append(Paragraph(heading, h_style))
        for text in paragraphs:
            story.append(Paragraph(text, body_style))
    pdf.build(story)
    return path


